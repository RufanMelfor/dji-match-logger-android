/**
 * DJI's CRC16 and CRC32.
 *
 * Both tables are copied verbatim from DJI's reference `custom_crc16.c`
 * and `custom_crc32.c` (MIT, see NOTICE) — generated from those
 * files rather than retyped. Do not regenerate them from a polynomial: what
 * makes these DJI-specific is the init value [INIT] of `0x3AA3`, not the
 * tables, and a wrong checksum is ignored by the camera in silence.
 *
 * The C code holds the tables in unsigned types. Kotlin's [IntArray] is
 * signed, so every intermediate value is masked back to width here — `and
 * 0xFFFF` for CRC16, and a logical `ushr` for CRC32 so the sign bit does not
 * propagate. That masking is the difference between a correctly copied table
 * and one that still produces wrong values.
 */
object DjiCrc {

    /** Init value for both, from `crc_init()` / `crc32_init()`. */
    const val INIT: Int = 0x3AA3

    /**
     * CRC16 over [length] bytes of [data].
     *
     * In a frame this covers the first 10 bytes, SOF through SEQ.
     */
    fun crc16(data: ByteArray, length: Int = data.size): Int {
        var crc = INIT
        for (i in 0 until length) {
            val index = (crc xor data[i].toInt()) and 0xFF
            crc = (CRC16_TABLE[index] xor (crc ushr 8)) and 0xFFFF
        }
        return crc and 0xFFFF
    }

    /**
     * CRC32 over [length] bytes of [data], returned as a raw 32-bit pattern.
     *
     * In a frame this covers everything from SOF up to the CRC32 field itself.
     * Int is exactly 32 bits wide, so no masking is needed — but the shift
     * must be [ushr] and not `shr`, or the sign bit smears through the result.
     */
    fun crc32(data: ByteArray, length: Int = data.size): Int {
        var crc = INIT
        for (i in 0 until length) {
            val index = (crc xor data[i].toInt()) and 0xFF
            crc = CRC32_TABLE[index] xor (crc ushr 8)
        }
        return crc
    }

